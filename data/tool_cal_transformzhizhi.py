#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
tool_cal_transformzhizhi.py —— 致知推理榜分数链式漂移校正工具
================================================================
【背景】致知推理榜（logic）每月滚动更新题库，模型分数随题库变难而漂移。
我们用相邻月"重测对"（同一模型两月分数都变化）线性拟合出每月变换：
    下月分 = a × 本月分 + b
把任意月份的分数链式对齐到 2026-08 题库标准。拟合公式来源见 fill_logic.py。

【月度变换公式】（a, b）：
  2025-02→03: y=1.239x−17.44    2025-10→11: y=0.971x−2.55
  2025-03→04: y=0.993x−6.16     2025-11→12: y=0.994x−3.75
  2025-04→05: y=0.978x−1.81     2025-12→01: y=0.942x+1.29
  2025-05→06: y=0.976x−3.09     2026-01→02: y=0.999x−5.78
  2025-06→07: 恒等               2026-02→03: y=0.980x+0.23
  2025-07→08: y=0.864x−5.29     2026-03→04: y=1.000x−2.97
  2025-08→09: y=0.978x−2.33     2026-04→05: y=0.990x−6.86
  2025-09→10: y=1.015x−0.11     2026-05→06: y=1.038x−3.29
                                 2026-06→07: y=0.918x−5.18
  2026-07→08: 恒等（08 即基准）
说明：2026-03→04 的一次项系数 1.000 是正常的——该月重测对的分数差值与
水平无关（全体约等量减 ~3 分），即题库"均匀变难"，拟合出平移而非缩放。

运行：python tool_cal_transformzhizhi.py
可修改下方变量：MODEL_LAST_MONTH（该模型最新出现的致知榜月份）、MODEL_SCORE（该月分数）
"""
# ================== 可修改变量 ==================
MODEL_LAST_MONTH = "2026-06"   # 模型最新出现的致知榜月份，如 "2026-06"
MODEL_SCORE = 55.8             # 该月在榜上的 中位分数
PRINT_STEPS = True             # 打印逐步变换过程
# =================================================

# 月度变换（2026-08 为基准；键=月份，值=(a, b)，恒等=(1,0)）
TRANS = {
    "2025-02": (1.239, -17.44), "2025-03": (0.993, -6.16),
    "2025-04": (0.978, -1.81),  "2025-05": (0.976, -3.09),
    "2025-06": (1.0, 0.0),      "2025-07": (0.864, -5.29),
    "2025-08": (0.978, -2.33),  "2025-09": (1.015, -0.11),
    "2025-10": (0.971, -2.55),  "2025-11": (0.994, -3.75),
    "2025-12": (0.942, 1.29),   "2026-01": (0.999, -5.78),
    "2026-02": (0.980, 0.23),   "2026-03": (1.000, -2.97),
    "2026-04": (0.990, -6.86),  "2026-05": (1.038, -3.29),
    "2026-06": (0.918, -5.18),  "2026-07": (1.0, 0.0),
}
MONTHS = sorted(TRANS)

def transform(month, score):
    """把 month 的分数链式变换到 2026-08 基准"""
    x = score
    steps = []
    for m in MONTHS:
        if month <= m <= "2026-06":   # 应用 T[m]（m→下月），06→07 后 07→08 恒等
            a, b = TRANS[m]
            y = a * x + b
            if PRINT_STEPS:
                steps.append(f"  {m}→下月: {x:.2f} → {a}×{x:.2f}{b:+.2f} = {y:.2f}")
            x = y
    return max(0.0, x), steps

if MODEL_LAST_MONTH not in TRANS and MODEL_LAST_MONTH != "2026-08":
    print(f"❌ 未知月份 {MODEL_LAST_MONTH}（可用月份见脚本内 TRANS 表）")
    raise SystemExit(1)

corr, steps = transform(MODEL_LAST_MONTH, MODEL_SCORE)
print(f"\n模型最新月份 {MODEL_LAST_MONTH}，榜上分数 {MODEL_SCORE}")
print(f"→ 校正到 2026-08 基准 = {corr:.2f}")
if PRINT_STEPS and steps:
    print("逐步过程：")
    print("\n".join(steps))
